# ============================================================
# TRANSLATION FUNCTION
# ============================================================

translate_soil_sensors <- function(df) {
  
  df$TIMESTAMP <- as.POSIXct(
    df$TIMESTAMP,
    tz = "UTC"
  )
  
  for (i in seq_along(soil_sensor_map)) {
    
    period <- soil_sensor_map[[i]]
    
    start <- as.POSIXct(
      period$start,
      tz = "UTC"
    )
    
    if (is.infinite(period$end)) {
      
      rows <- df$TIMESTAMP >= start
      
    } else {
      
      end <- as.POSIXct(
        period$end,
        tz = "UTC"
      )
      
      rows <- df$TIMESTAMP >= start &
        df$TIMESTAMP < end
    }
    
    # --------------------------------------------------------
    # TEMPERATURE
    # --------------------------------------------------------
    
    for (j in seq_along(current_temperature)) {
      
      old_name <- period$temperature[j]
      new_name <- current_temperature[j]
      
      if (
        !is.na(old_name) &&
        old_name %in% names(df)
      ) {
        
        if (!new_name %in% names(df)) {
          df[[new_name]] <- NA_real_
        }
        
        df[[new_name]][rows] <- df[[old_name]][rows]
      }
    }
    
    
    # --------------------------------------------------------
    # MOISTURE
    # --------------------------------------------------------
    
    for (j in seq_along(current_moisture)) {
      
      old_name <- period$moisture[j]
      new_name <- current_moisture[j]
      
      if (
        !is.na(old_name) &&
        old_name %in% names(df)
      ) {
        
        if (!new_name %in% names(df)) {
          df[[new_name]] <- NA_real_
        }
        
        df[[new_name]][rows] <- df[[old_name]][rows]
      }
    }
  }
  
  df
}